#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum OpCode {
    Constant,
    Nil,
    True,
    False,
    Pop,
    Dup,

    DefGlobal,
    GetGlobal,
    SetGlobal,
    GetLocal,
    SetLocal,
    GetUpvalue,
    SetUpvalue,

    Add,
    Sub,
    Mul,
    Div,
    Mod,
    Neg,

    Equal,
    NotEqual,
    Greater,
    GreaterEqual,
    Less,
    LessEqual,
    Not,
    In,
    NotIn,

    IsPositive,
    IsNegative,
    IsZero,
    IsEven,
    IsOdd,
    IsEmpty,
    IsSomething,

    Jump,
    JumpIfFalse,
    Loop,

    PushTry,
    PopTry,
    Raise,

    Call,
    Closure,
    Return,

    BuildList,
    BuildMap,
    IndexGet,
    IndexSet,
    GetProperty,
    SetProperty,

    Say,
    AddToList,
    GetModule,
    Serve,
    Respond,
    Validate,
    HttpRequest,
    Class,
    Inherit,
    Method,
    Constructor,
    New,
    CallParent,
    IsInstance,
    TypeOf,
    IsString,
    IsNumber,
    IsInteger,
    IsFloat,
    IsBoolean,
    IsList,
    IsMap,
    IsFunction,
    Halt,
}

impl OpCode {
    pub fn from_u8(byte: u8) -> Option<Self> {
        match byte {
            x if x == OpCode::Constant as u8 => Some(OpCode::Constant),
            x if x == OpCode::Nil as u8 => Some(OpCode::Nil),
            x if x == OpCode::True as u8 => Some(OpCode::True),
            x if x == OpCode::False as u8 => Some(OpCode::False),
            x if x == OpCode::Pop as u8 => Some(OpCode::Pop),
            x if x == OpCode::Dup as u8 => Some(OpCode::Dup),
            x if x == OpCode::DefGlobal as u8 => Some(OpCode::DefGlobal),
            x if x == OpCode::GetGlobal as u8 => Some(OpCode::GetGlobal),
            x if x == OpCode::SetGlobal as u8 => Some(OpCode::SetGlobal),
            x if x == OpCode::GetLocal as u8 => Some(OpCode::GetLocal),
            x if x == OpCode::SetLocal as u8 => Some(OpCode::SetLocal),
            x if x == OpCode::GetUpvalue as u8 => Some(OpCode::GetUpvalue),
            x if x == OpCode::SetUpvalue as u8 => Some(OpCode::SetUpvalue),
            x if x == OpCode::Add as u8 => Some(OpCode::Add),
            x if x == OpCode::Sub as u8 => Some(OpCode::Sub),
            x if x == OpCode::Mul as u8 => Some(OpCode::Mul),
            x if x == OpCode::Div as u8 => Some(OpCode::Div),
            x if x == OpCode::Mod as u8 => Some(OpCode::Mod),
            x if x == OpCode::Neg as u8 => Some(OpCode::Neg),
            x if x == OpCode::Equal as u8 => Some(OpCode::Equal),
            x if x == OpCode::NotEqual as u8 => Some(OpCode::NotEqual),
            x if x == OpCode::Greater as u8 => Some(OpCode::Greater),
            x if x == OpCode::GreaterEqual as u8 => Some(OpCode::GreaterEqual),
            x if x == OpCode::Less as u8 => Some(OpCode::Less),
            x if x == OpCode::LessEqual as u8 => Some(OpCode::LessEqual),
            x if x == OpCode::Not as u8 => Some(OpCode::Not),
            x if x == OpCode::In as u8 => Some(OpCode::In),
            x if x == OpCode::NotIn as u8 => Some(OpCode::NotIn),
            x if x == OpCode::IsPositive as u8 => Some(OpCode::IsPositive),
            x if x == OpCode::IsNegative as u8 => Some(OpCode::IsNegative),
            x if x == OpCode::IsZero as u8 => Some(OpCode::IsZero),
            x if x == OpCode::IsEven as u8 => Some(OpCode::IsEven),
            x if x == OpCode::IsOdd as u8 => Some(OpCode::IsOdd),
            x if x == OpCode::IsEmpty as u8 => Some(OpCode::IsEmpty),
            x if x == OpCode::IsSomething as u8 => Some(OpCode::IsSomething),
            x if x == OpCode::Jump as u8 => Some(OpCode::Jump),
            x if x == OpCode::JumpIfFalse as u8 => Some(OpCode::JumpIfFalse),
            x if x == OpCode::Loop as u8 => Some(OpCode::Loop),
            x if x == OpCode::PushTry as u8 => Some(OpCode::PushTry),
            x if x == OpCode::PopTry as u8 => Some(OpCode::PopTry),
            x if x == OpCode::Raise as u8 => Some(OpCode::Raise),
            x if x == OpCode::Call as u8 => Some(OpCode::Call),
            x if x == OpCode::Closure as u8 => Some(OpCode::Closure),
            x if x == OpCode::Return as u8 => Some(OpCode::Return),
            x if x == OpCode::BuildList as u8 => Some(OpCode::BuildList),
            x if x == OpCode::BuildMap as u8 => Some(OpCode::BuildMap),
            x if x == OpCode::IndexGet as u8 => Some(OpCode::IndexGet),
            x if x == OpCode::IndexSet as u8 => Some(OpCode::IndexSet),
            x if x == OpCode::GetProperty as u8 => Some(OpCode::GetProperty),
            x if x == OpCode::SetProperty as u8 => Some(OpCode::SetProperty),
            x if x == OpCode::Say as u8 => Some(OpCode::Say),
            x if x == OpCode::AddToList as u8 => Some(OpCode::AddToList),
            x if x == OpCode::GetModule as u8 => Some(OpCode::GetModule),
            x if x == OpCode::Serve as u8 => Some(OpCode::Serve),
            x if x == OpCode::Respond as u8 => Some(OpCode::Respond),
            x if x == OpCode::Validate as u8 => Some(OpCode::Validate),
            x if x == OpCode::HttpRequest as u8 => Some(OpCode::HttpRequest),
            x if x == OpCode::Class as u8 => Some(OpCode::Class),
            x if x == OpCode::Inherit as u8 => Some(OpCode::Inherit),
            x if x == OpCode::Method as u8 => Some(OpCode::Method),
            x if x == OpCode::Constructor as u8 => Some(OpCode::Constructor),
            x if x == OpCode::New as u8 => Some(OpCode::New),
            x if x == OpCode::CallParent as u8 => Some(OpCode::CallParent),
            x if x == OpCode::IsInstance as u8 => Some(OpCode::IsInstance),
            x if x == OpCode::TypeOf as u8 => Some(OpCode::TypeOf),
            x if x == OpCode::IsString as u8 => Some(OpCode::IsString),
            x if x == OpCode::IsNumber as u8 => Some(OpCode::IsNumber),
            x if x == OpCode::IsInteger as u8 => Some(OpCode::IsInteger),
            x if x == OpCode::IsFloat as u8 => Some(OpCode::IsFloat),
            x if x == OpCode::IsBoolean as u8 => Some(OpCode::IsBoolean),
            x if x == OpCode::IsList as u8 => Some(OpCode::IsList),
            x if x == OpCode::IsMap as u8 => Some(OpCode::IsMap),
            x if x == OpCode::IsFunction as u8 => Some(OpCode::IsFunction),
            x if x == OpCode::Halt as u8 => Some(OpCode::Halt),
            _ => None,
        }
    }
}
