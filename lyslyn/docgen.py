"""Automated Documentation Generator for Lyslyn projects."""
import os
import re
from typing import List, Dict, Any, Optional
from .lexer import Lexer
from .parser import Parser
from .ast_nodes import Program, FunctionStmt, RouteStmt, SetStmt, VariableExpr


class DocItem:
    def __init__(self, kind: str, name: str, signature: str, description: str, line: int):
        self.kind = kind
        self.name = name
        self.signature = signature
        self.description = description
        self.line = line


def extract_docs(filepath: str) -> List[DocItem]:
    with open(filepath, "r", encoding="utf-8") as f:
        source = f.read()

    lines = source.splitlines()
    tokens = Lexer(source, filename=filepath).tokenize()
    program = Parser(tokens, filename=filepath, source=source).parse()

    docs: List[DocItem] = []

    def get_preceding_doc(line_idx: int) -> str:
        doc_lines = []
        i = line_idx - 2
        while i >= 0:
            l = lines[i].strip()
            if l.startswith("///") or l.startswith("#"):
                clean = l.lstrip("/# ").strip()
                if not clean.startswith("===") and not clean.startswith("---"):
                    doc_lines.insert(0, clean)
                i -= 1
            else:
                break
        return "\n".join(doc_lines).strip()

    for stmt in program.statements:
        if isinstance(stmt, FunctionStmt):
            desc = get_preceding_doc(stmt.line)
            sig = f"fn {stmt.name}({', '.join(stmt.params)})"
            docs.append(DocItem("function", stmt.name, sig, desc, stmt.line))

        elif isinstance(stmt, SetStmt) and stmt.is_constant and isinstance(stmt.target, VariableExpr):
            desc = get_preceding_doc(stmt.line)
            sig = f"constant {stmt.target.name}"
            docs.append(DocItem("constant", stmt.target.name, sig, desc, stmt.line))

    return docs


def generate_markdown_doc(filepath: str, docs: List[DocItem]) -> str:
    mod_name = os.path.basename(filepath)
    md = [f"# Module `{mod_name}`\n", f"> Generated by Lyslyn Doc Engine\n"]

    functions = [d for d in docs if d.kind == "function"]
    constants = [d for d in docs if d.kind == "constant"]

    if constants:
        md.append("## Constants\n")
        for c in constants:
            md.append(f"### `{c.name}`")
            if c.description:
                md.append(f"{c.description}\n")
            md.append(f"```lys\n{c.signature}\n```\n")

    if functions:
        md.append("## Functions\n")
        for fn in functions:
            md.append(f"### `{fn.name}`")
            if fn.description:
                md.append(f"{fn.description}\n")
            md.append(f"```lys\n{fn.signature}\n```\n")

    return "\n".join(md)
